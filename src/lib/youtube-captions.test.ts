import { beforeEach, describe, expect, it, vi } from "vitest";

const lib = vi.hoisted(() => ({ listLanguages: vi.fn(), fetchTranscript: vi.fn() }));

// The real error classes, with the two network calls replaced.
vi.mock("youtube-transcript-plus", async () => {
  const actual = await vi.importActual<typeof import("youtube-transcript-plus")>("youtube-transcript-plus");
  return { ...actual, listLanguages: lib.listLanguages, fetchTranscript: lib.fetchTranscript };
});

import {
  YoutubeTranscriptDisabledError, YoutubeTranscriptNotAvailableError, YoutubeTranscriptTooManyRequestError,
  YoutubeTranscriptVideoUnavailableError,
} from "youtube-transcript-plus";
import { chooseTrack, fetchYouTubeCaptions, isSoundCue, normalizeSegments } from "./youtube-captions";

const track = (languageCode: string, isAutoGenerated = false) => ({ languageCode, languageName: languageCode, isAutoGenerated });
const ID = "abcdefghijk";

describe("chooseTrack", () => {
  it("takes the auto track's language as the spoken language", () => {
    expect(chooseTrack([track("ar"), track("en", true), track("fr")])).toEqual({ languageCode: "en", kind: "auto" });
  });

  it("prefers a creator-written track in the spoken language over the generated one", () => {
    expect(chooseTrack([track("ar"), track("en"), track("en", true)])).toEqual({ languageCode: "en", kind: "manual" });
    // Regional variants of the spoken language count as the same language.
    expect(chooseTrack([track("en-GB"), track("en", true)])).toEqual({ languageCode: "en-GB", kind: "manual" });
  });

  it("reports the kind of the track that will actually be downloaded when the auto one is listed first", () => {
    // The package fetches the first track with a matching code, so that is what the label must describe.
    expect(chooseTrack([track("en", true), track("en")])).toEqual({ languageCode: "en", kind: "auto" });
  });

  it("with no generated track prefers English, then the first track", () => {
    expect(chooseTrack([track("fr"), track("en")])).toEqual({ languageCode: "en", kind: "manual" });
    expect(chooseTrack([track("fr"), track("de")])).toEqual({ languageCode: "fr", kind: "manual" });
    expect(chooseTrack([track("it", true)])).toEqual({ languageCode: "it", kind: "auto" });
  });

  it("returns null for a video with no tracks", () => {
    expect(chooseTrack([])).toBeNull();
  });
});

describe("normalizeSegments", () => {
  it("keeps the original wording, decodes entities (even double-encoded ones) and converts offset+duration to start/end", () => {
    const { segments, text } = normalizeSegments([
      { text: "this shot is called a speed Rin it&#39;s a", offset: 0, duration: 5.04 },
      { text: "I said, &quot;Is there?&quot; Do\nyou", offset: 3.48, duration: 3.96 },
      { text: "Tom &amp;#39;s", offset: 7.44, duration: 1 },
    ]);
    expect(segments).toEqual([
      { start: 0, end: 5.04, text: "this shot is called a speed Rin it's a" },
      { start: 3.48, end: 7.44, text: 'I said, "Is there?" Do you' },
      { start: 7.44, end: 8.44, text: "Tom 's" },
    ]);
    expect(text).toBe(`${segments.map((s) => s.text).join(" ")}`);
  });

  it("keeps sound cues in the segments but not in the spoken text", () => {
    const { segments, text } = normalizeSegments([
      { text: "[Music]", offset: 0, duration: 2 },
      { text: "hello there", offset: 2, duration: 2 },
      { text: "(applause)", offset: 4, duration: 1 },
    ]);
    expect(segments).toHaveLength(3);
    expect(text).toBe("hello there");
  });

  it("has no text when only cues were captioned, and skips empty or untimed lines", () => {
    expect(normalizeSegments([{ text: "[Music]", offset: 0, duration: 2 }]).text).toBeNull();
    const { segments } = normalizeSegments([
      { text: "   ", offset: 0, duration: 1 },
      { text: "no time", offset: Number.NaN, duration: 1 },
      { text: "ok", offset: 1, duration: 0 },
    ]);
    expect(segments).toEqual([{ start: 1, end: null, text: "ok" }]);
  });

  it("does not treat speech containing brackets as a cue", () => {
    expect(isSoundCue("[Music]")).toBe(true);
    expect(isSoundCue("♪ ♪")).toBe(true);
    expect(isSoundCue("I said [Music] was loud")).toBe(false);
    expect(isSoundCue("hello")).toBe(false);
  });
});

describe("fetchYouTubeCaptions", () => {
  beforeEach(() => {
    lib.listLanguages.mockReset();
    lib.fetchTranscript.mockReset();
  });

  it("returns the chosen track's captions with kind, language and the other languages", async () => {
    lib.listLanguages.mockResolvedValue([track("ar"), track("en", true), track("fr")]);
    lib.fetchTranscript.mockResolvedValue([{ text: "hi there", offset: 0.5, duration: 2, lang: "en" }]);
    const out = await fetchYouTubeCaptions(ID);
    expect(out).toEqual({
      ok: true,
      captions: {
        language: "en", kind: "auto", text: "hi there", otherLanguages: ["ar", "fr"],
        segments: [{ start: 0.5, end: 2.5, text: "hi there" }],
      },
    });
    expect(lib.fetchTranscript.mock.calls[0][1]).toMatchObject({ lang: "en" });
  });

  it("applies a timeout signal and no retries or proxies", async () => {
    lib.listLanguages.mockResolvedValue([track("en", true)]);
    lib.fetchTranscript.mockResolvedValue([{ text: "x", offset: 0, duration: 1, lang: "en" }]);
    await fetchYouTubeCaptions(ID);
    const config = lib.fetchTranscript.mock.calls[0][1];
    expect(config.signal).toBeInstanceOf(AbortSignal);
    expect(config).not.toHaveProperty("retries");
    expect(config).not.toHaveProperty("videoFetch");
    expect(config).not.toHaveProperty("playerFetch");
  });

  it.each([
    [new YoutubeTranscriptDisabledError(ID), "none"],
    [new YoutubeTranscriptNotAvailableError(ID), "none"],
    [new YoutubeTranscriptVideoUnavailableError(ID), "unavailable"],
    [new YoutubeTranscriptTooManyRequestError(), "rate_limited"],
    [new TypeError("fetch failed"), "failed"],
    [Object.assign(new Error("x"), { name: "TimeoutError" }), "failed"],
  ])("maps %s to %s without throwing", async (err, reason) => {
    lib.listLanguages.mockRejectedValue(err);
    expect(await fetchYouTubeCaptions(ID)).toMatchObject({ ok: false, reason });
  });

  it("reports no captions for a video with an empty track list", async () => {
    lib.listLanguages.mockResolvedValue([]);
    expect(await fetchYouTubeCaptions(ID)).toMatchObject({ ok: false, reason: "none" });
    expect(lib.fetchTranscript).not.toHaveBeenCalled();
  });

  it("reports no captions when the track holds only sound descriptions", async () => {
    lib.listLanguages.mockResolvedValue([track("en", true)]);
    lib.fetchTranscript.mockResolvedValue([{ text: "[Music]", offset: 0, duration: 5, lang: "en" }]);
    expect(await fetchYouTubeCaptions(ID)).toMatchObject({ ok: false, reason: "none", message: expect.stringMatching(/no spoken words/) });
  });

  it("never calls YouTube for a malformed video id", async () => {
    expect(await fetchYouTubeCaptions("../etc/passwd")).toMatchObject({ ok: false, reason: "failed" });
    expect(lib.listLanguages).not.toHaveBeenCalled();
  });

  it("never echoes raw error text", async () => {
    lib.listLanguages.mockRejectedValue(new Error("secret internal detail http://x"));
    const out = await fetchYouTubeCaptions(ID);
    expect(out.ok === false && out.message).not.toContain("secret");
  });
});

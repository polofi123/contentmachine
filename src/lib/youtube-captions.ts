// Best-effort retrieval of the captions a public YouTube video already has.
// Server-only; never touches the database.
//
// This uses the maintained `youtube-transcript-plus` package, which reads the
// same caption tracks the YouTube web player offers to any viewer. There is no
// login, no cookie, no proxy and no retry loop: one request to list the tracks,
// one to download the chosen one, a hard timeout, and any failure is returned as
// a plain outcome for the caller to fall back from. (The package re-reads the
// watch page and player data for each of its two calls, so a run is a handful
// of requests, not two.) It is an unofficial
// endpoint, so it can stop working when YouTube changes it — nothing may depend
// on it succeeding.

import {
  fetchTranscript, listLanguages, YoutubeTranscriptDisabledError, YoutubeTranscriptNotAvailableError,
  YoutubeTranscriptNotAvailableLanguageError, YoutubeTranscriptTooManyRequestError,
  YoutubeTranscriptVideoUnavailableError, type CaptionTrackInfo,
} from "youtube-transcript-plus";
import { decodeEntities, type TranscriptSegment } from "./video-analysis";

const TIMEOUT_MS = 15_000;
const MAX_SEGMENTS = 2000;
const VIDEO_ID = /^[\w-]{11}$/;

export type CaptionKind = "manual" | "auto";

export type FetchedCaptions = {
  language: string;
  /** "manual": written or uploaded by the creator. "auto": YouTube's speech recognition. */
  kind: CaptionKind;
  /** Every line as YouTube returned it (entities decoded), including sound cues like [Music]. */
  segments: TranscriptSegment[];
  /** The spoken words only: sound cues removed. Null when nothing but cues remained. */
  text: string | null;
  /** Language codes of the other tracks this video has, for the note shown to the user. */
  otherLanguages: string[];
};

export type CaptionOutcome =
  | { ok: true; captions: FetchedCaptions }
  | { ok: false; reason: "none" | "unavailable" | "rate_limited" | "failed"; message: string };

const baseLang = (code: string) => code.toLowerCase().split("-")[0];

/**
 * Picks the track to download. The speech-recognition track is in the language
 * the video is actually spoken in, so that language wins; within it a
 * creator-written track is preferred to the generated one. With no generated
 * track, English if offered, else the first.
 */
export function chooseTrack(tracks: CaptionTrackInfo[]): { languageCode: string; kind: CaptionKind } | null {
  if (!tracks.length) return null;
  const auto = tracks.find((t) => t.isAutoGenerated);
  const pick = auto
    ? tracks.find((t) => !t.isAutoGenerated && baseLang(t.languageCode) === baseLang(auto.languageCode)) ?? auto
    : tracks.find((t) => baseLang(t.languageCode) === "en") ?? tracks[0];
  // The package downloads the first track listed with a given code, so that
  // track is the one whose kind is reported.
  const served = tracks.find((t) => t.languageCode === pick.languageCode) ?? pick;
  return { languageCode: pick.languageCode, kind: served.isAutoGenerated ? "auto" : "manual" };
}

const SOUND_CUE = /^\s*(?:[[(][^\])]{1,40}[\])]\s*)+$|^[\s♪♫]+$/;
/** Bracketed sound descriptions such as "[Music]" or "(applause)". Not speech. */
export const isSoundCue = (text: string) => SOUND_CUE.test(text);

type RawSegment = { text: string; offset: number; duration: number };

/** Decodes entities, flattens line breaks and converts offset+duration into start/end seconds. */
export function normalizeSegments(raw: RawSegment[]): { segments: TranscriptSegment[]; text: string | null } {
  const segments: TranscriptSegment[] = [];
  for (const r of raw.slice(0, MAX_SEGMENTS)) {
    const text = decodeEntities(String(r.text ?? "")).replace(/\s+/g, " ").trim();
    if (!text || !Number.isFinite(r.offset) || r.offset < 0) continue;
    const start = Math.round(r.offset * 1000) / 1000;
    const end = Number.isFinite(r.duration) && r.duration > 0 ? Math.round((r.offset + r.duration) * 1000) / 1000 : null;
    segments.push({ start, end, text });
  }
  const spoken = segments.filter((s) => !isSoundCue(s.text)).map((s) => s.text);
  return { segments, text: spoken.length ? spoken.join(" ") : null };
}

function failure(err: unknown): Extract<CaptionOutcome, { ok: false }> {
  if (err instanceof YoutubeTranscriptTooManyRequestError) {
    return { ok: false, reason: "rate_limited", message: "YouTube is limiting caption requests from this connection right now." };
  }
  if (err instanceof YoutubeTranscriptVideoUnavailableError) {
    return { ok: false, reason: "unavailable", message: "YouTube says this video is unavailable (private, removed or restricted)." };
  }
  if (
    err instanceof YoutubeTranscriptDisabledError || err instanceof YoutubeTranscriptNotAvailableError ||
    err instanceof YoutubeTranscriptNotAvailableLanguageError
  ) {
    return { ok: false, reason: "none", message: "This video has no captions available." };
  }
  if (err instanceof Error && (err.name === "TimeoutError" || err.name === "AbortError")) {
    return { ok: false, reason: "failed", message: "YouTube did not answer in time." };
  }
  return { ok: false, reason: "failed", message: "The captions could not be retrieved from YouTube." };
}

/** Never throws. */
export async function fetchYouTubeCaptions(videoId: string): Promise<CaptionOutcome> {
  if (!VIDEO_ID.test(videoId)) return { ok: false, reason: "failed", message: "Not a valid YouTube video id." };
  const signal = AbortSignal.timeout(TIMEOUT_MS);
  try {
    const tracks = await listLanguages(videoId, { signal });
    const track = chooseTrack(tracks);
    if (!track) return { ok: false, reason: "none", message: "This video has no captions available." };

    const raw = await fetchTranscript(videoId, { lang: track.languageCode, signal });
    const { segments, text } = normalizeSegments(raw);
    if (!text) {
      return { ok: false, reason: "none", message: "The captions contain no spoken words (only sound descriptions)." };
    }
    return {
      ok: true,
      captions: {
        language: track.languageCode,
        kind: track.kind,
        segments,
        text,
        otherLanguages: [...new Set(tracks.map((t) => t.languageCode).filter((c) => c !== track.languageCode))],
      },
    };
  } catch (err) {
    return failure(err);
  }
}
